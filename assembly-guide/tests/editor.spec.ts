test('surface placement uses a real model hit, ignores drags, and saves position and insertion direction', async ({ page }) => {
    await open(page, 'figure-stand');
    await page.getByRole('button', { name: '3Dで固定位置を追加', exact: true }).click();
    await page.getByRole('button', { name: '正面', exact: true }).click();
    const rect = (await page.locator('#viewport canvas').boundingBox())!, aspect = rect.width / rect.height, half = 36 * Math.PI / 360, distance = Math.hypot(1, 1.5, .04) / 2 / Math.sin(Math.min(half, Math.atan(Math.tan(half) * aspect))) * 1.2;
    const camera = new PerspectiveCamera(36, aspect, distance / 10000, distance * 100);
    camera.position.set(0, .75, distance);
    camera.lookAt(0, .75, 0);
    camera.updateMatrixWorld();
    const p = new Vector3(.014, .475, .02).project(camera), x = rect.x + (p.x + 1) * rect.width / 2, y = rect.y + (1 - p.y) * rect.height / 2;
    await page.mouse.move(x, y);
    await page.mouse.down();
    await page.mouse.move(x + 30, y + 15, { steps: 6 });
    await page.mouse.up();
    await expect(page.locator('.fixing-label')).toHaveCount(1);
    await page.getByRole('button', { name: '正面', exact: true }).click();
    await page.mouse.click(x, y);
    await expect(page.locator('.fixing-label')).toHaveCount(2);
    await page.getByRole('button', { name: '手順を保存', exact: true }).click();
    await expect(page.getByRole('button', { name: '手順を保存', exact: true })).toBeDisabled();
    await expect(page.getByText('保存済みの手順を表示中', { exact: true })).toBeVisible();
    const saved = JSON.parse(await readFile('public/guides/figure-stand.json', 'utf8')), marker = saved.steps[0].markers[1];
    expect(marker.type).toBe('screw');
    expect(marker.position[0]).toBeCloseTo(14, 1);
    expect(marker.position[1]).toBeCloseTo(475, 1);
    expect(marker.position[2]).toBeCloseTo(20, 1);
    expect(Math.hypot(...marker.direction)).toBeCloseTo(1, 6);
    expect(marker.direction[2]).toBeLessThan(-.99);
});
test('local endpoints enforce origin, body IDs, schema and revision conflicts', async ({ request }) => {
    const base = 'http://127.0.0.1:5274', headers = { Origin: base };
    expect(await (await request.get('/__guide/runtime')).json()).toEqual({ app: 'fusion-assembly-guide', mode: 'admin' });
    expect((await request.post('/__guide/runtime', { headers, data: {} })).status()).toBe(405);
    expect((await request.get('/__guide/runtime', { headers: { Host: 'other.example' } })).status()).toBe(403);
    const initial = await (await request.get('/__guide/config?product=pillar-decoration')).json();
    expect((await request.post('/__guide/save', { headers: { Origin: 'https://other.example' }, data: {} })).status()).toBe(403);
    const invalid = structuredClone(initial.guide);
    invalid.steps[0].bodyIds = ['build:999/object:999'];
    expect((await request.post('/__guide/save', { headers, data: { productId: 'pillar-decoration', revision: initial.revision, guide: invalid } })).status()).toBe(400);
    expect((await request.post('/__guide/save', { headers, data: { productId: 'pillar-decoration', revision: 'stale', guide: initial.guide } })).status()).toBe(409);
    const next = structuredClone(initial.guide);
    next.steps[0].description = '競合検証用の変更';
    const saved = await request.post('/__guide/save', { headers, data: { productId: 'pillar-decoration', revision: initial.revision, guide: next } });
    expect(saved.status()).toBe(200);
    expect((await saved.json()).revision).not.toBe(initial.revision);
    expect((await request.post('/__guide/save', { headers, data: { productId: 'pillar-decoration', revision: initial.revision, guide: next } })).status()).toBe(409);
});

