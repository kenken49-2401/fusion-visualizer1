test('guide groups reject unknown or overlapping members and persist in the existing guide endpoint', async ({ request }) => {
    const headers = { Origin: 'http://127.0.0.1:5274' }, productId = 'standing-desk-small';
    const initial = await (await request.get(`/__guide/config?product=${productId}`)).json();
    const group = { id: 'test-pair', name: '机の組', bodyIds: ['build:0/object:1', 'build:1/object:3'] };
    for (const groups of [[{ ...group, bodyIds: ['build:999/object:1'] }], [group, { ...group, id: 'duplicate', name: '重複所属' }]]) {
        const guide = { ...initial.guide, groups };
        expect((await request.post('/__guide/save', { headers, data: { productId, revision: initial.revision, guide } })).status()).toBe(400);
    }
    const guide = { ...initial.guide, groups: [group] };
    const response = await request.post('/__guide/save', { headers, data: { productId, revision: initial.revision, guide } });
    expect(response.status()).toBe(200); expect((await response.json()).guide.groups).toEqual([group]);
    expect((await request.post('/__guide/save', { headers, data: { productId, revision: initial.revision, guide } })).status()).toBe(409);
});
